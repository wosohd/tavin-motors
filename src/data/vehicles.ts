export function getVehiclesByStatus(status: VehicleStatus) {
  return vehicles.filter((vehicle) => vehicle.status === status);
}

export function getVehicleBySlug(slug: string) {
  return vehicles.find((vehicle) => vehicle.slug === slug);
}

export function getRelatedVehicles(vehicle: Vehicle, limit = 3) {
  return vehicles
    .filter(
      (candidate) =>
        candidate.id !== vehicle.id &&
        candidate.status === vehicle.status &&
        (candidate.make === vehicle.make ||
          candidate.bodyType === vehicle.bodyType),
    )
    .slice(0, limit);
}

export function formatVehiclePrice(price: number) {
  return new Intl.NumberFormat("en-KE", {
    style: "currency",
    currency: "KES",
    maximumFractionDigits: 0,
  }).format(price);
}

export function formatMileage(mileage: number) {
  return new Intl.NumberFormat("en-KE").format(mileage);
}