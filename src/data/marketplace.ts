export function getMarketplaceListingBySlug(slug: string) {
  return marketplaceListings.find(
    (listing) => listing.slug === slug,
  );
}

export function getRelatedMarketplaceListings(
  listing: MarketplaceListing,
  limit = 3,
) {
  return marketplaceListings
    .filter(
      (candidate) =>
        candidate.id !== listing.id &&
        (candidate.make === listing.make ||
          candidate.bodyType === listing.bodyType),
    )
    .slice(0, limit);
}

export function formatListingDate(date: string) {
  return new Intl.DateTimeFormat("en-KE", {
    day: "numeric",
    month: "short",
    year: "numeric",
  }).format(new Date(date));
}